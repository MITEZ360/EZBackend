import type { Component } from 'vue'
import {
  Avatar,
  Bell,
  ChatDotRound,
  Clock,
  Coin,
  Connection,
  Document,
  Folder,
  Guide,
  Grid,
  Key,
  Menu as MenuIcon,
  Monitor,
  Notebook,
  OfficeBuilding,
  Odometer,
  Operation,
  Reading,
  Setting,
  Share,
  Trophy,
  TrendCharts,
  User,
  Warning,
  UserFilled,
} from '@element-plus/icons-vue'

/** 后端菜单的 icon 字段是语义字符串，这里映射到实际图标组件 */
export const menuIcons: Record<string, Component> = {
  dashboard: Odometer,
  settings: Setting,
  users: User,
  user: UserFilled,
  shield: Avatar,
  menu: MenuIcon,
  org: OfficeBuilding,
  book: Notebook,
  sliders: Operation,
  trophy: Trophy,
  bell: Bell,
  message: ChatDotRound,
  server: Monitor,
  clock: Clock,
  folder: Folder,
  grid: Grid,
  login: Key,
  key: Key,
  news: Reading,
  'file-text': Document,
  wifi: Connection,
  activity: TrendCharts,
  route: Guide,
  cache: Coin,
  cluster: Connection,
  flow: Share,
  share: Share,
  history: Clock,
  alert: Warning,
}

export function resolveIcon(name?: string): Component {
  if (!name) return MenuIcon
  return menuIcons[name] ?? MenuIcon
}
